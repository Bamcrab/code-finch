export interface LocationDiscovery {
  id: string;
  name: string;
  emoji: string;
  category: string;
  blurb: string;
}

export interface LocationItem {
  id: string;
  name: string;
  art: string;
  color: string;
  accent?: string;
  price: number;
}

export interface LocationDef {
  id: string;
  name: string;
  region: string;
  emoji: string;
  blurb: string;
  sky: [string, string];
  ground: string;
  hill: string;
  discoveries: LocationDiscovery[];
  items: LocationItem[];
}

function D(id: string, name: string, emoji: string, category: string, blurb: string): LocationDiscovery {
  return { id, name, emoji, category, blurb };
}

function I(id: string, name: string, art: string, color: string, price = 450, accent?: string): LocationItem {
  return { id, name, art, color, price, accent };
}

